// Writes src/generated/assets.ts: the schema files as string constants and the YAML policies as parsed
// objects (parsed here, so the API needs no YAML parser at runtime).
//
//     npm run gen
//
// The API reads these texts at runtime (capability detection, the schema excerpts in the TypeDB
// Advantage panel, the engagement and connection policies). Netlify's edge runtime cannot read the
// repository's files, so they are generated into a module instead. A test fails if this is stale.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
export const OUT = join(ROOT, "api", "src", "generated", "assets.ts");

/** schema/migrations/NNN-*.tql in number order (the same rule as database.ts). */
export function migrationFiles(): string[] {
  const names = readdirSync(join(ROOT, "schema", "migrations")).filter((n) => /^[0-9][0-9][0-9]-.*\.tql$/.test(n)).sort();
  const numbers = names.map((n) => n.slice(0, 3));
  if (new Set(numbers).size !== numbers.length) throw new Error(`two migrations share a number: ${numbers}`);
  return names.map((n) => `schema/migrations/${n}`);
}

function read(path: string): string {
  return readFileSync(join(ROOT, path), "utf8");
}

/** The module text, from the files as they are now. */
export function render(): string {
  const schema = ["schema/schema.tql", "schema/functions.tql", ...migrationFiles()].map((path) => ({ path, text: read(path) }));
  const lines = [
    "// GENERATED by api/scripts/gen.ts (npm run gen) from the schema and config files. Do not edit by hand.",
    "// The edge runtime cannot read the repository, so the texts the API needs at runtime live here.",
    "",
    "export interface TextFile {",
    "  path: string;",
    "  text: string;",
    "}",
    "",
    "/** schema/schema.tql, schema/functions.tql, then each migration in number order: what built the database. */",
    "export const SCHEMA_FILES: TextFile[] = [",
    ...schema.map((f) => `  { path: ${JSON.stringify(f.path)}, text: ${JSON.stringify(f.text)} },`),
    "];",
    "",
    "/** config/engagement-policy.yaml, parsed. */",
    `export const ENGAGEMENT_POLICY = ${JSON.stringify(parse(read("config/engagement-policy.yaml")))};`,
    "",
    "/** config/connection-policy.yaml, parsed. */",
    `export const CONNECTION_POLICY = ${JSON.stringify(parse(read("config/connection-policy.yaml")))};`,
    "",
  ];
  return lines.join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, render());
  console.log(`wrote ${OUT}`);
}
