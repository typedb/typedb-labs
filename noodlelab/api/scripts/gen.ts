// Writes src/generated/assets.ts: the schema, the seed files and the 3D model maps as string constants.
//
//     npm run gen
//
// The backend must not read the repository's files when it runs (Netlify's edge runtime has no files), so
// the texts it needs are generated into a TypeScript module. A test fails when this file is out of date.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const project = fileURLToPath(new URL("../..", import.meta.url));
const read = (path: string) => readFileSync(join(project, path), "utf8");

export function render(): string {
  const seed = readdirSync(join(project, "data/seed")).filter((f) => f.endsWith(".yaml")).sort();
  const maps = readdirSync(join(project, "web/public/assets")).filter((f) => f.endsWith(".map.json")).sort();
  const lines = [
    "// GENERATED by `npm run gen` (api/scripts/gen.ts) from schema/, data/seed/ and web/public/assets/*.map.json.",
    "// Do not edit by hand: edit those files and run `npm run gen`. A test checks this file is current.",
    "",
    `export const SCHEMA_TQL = ${JSON.stringify(read("schema/schema.tql"))};`,
    "",
    `export const FUNCTIONS_TQL = ${JSON.stringify(read("schema/functions.tql"))};`,
    "",
    "/** data/seed/<name>.yaml, by file name */",
    "export const SEED_YAML: Record<string, string> = {",
    ...seed.map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(read(`data/seed/${f}`))},`),
    "};",
    "",
    "/** web/public/assets/<asset>.map.json, by file name: which 3D node draws each component */",
    "export const VISUAL_MAPS: Record<string, string> = {",
    ...maps.map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(read(`web/public/assets/${f}`))},`),
    "};",
    "",
  ];
  return lines.join("\n");
}

export const target = fileURLToPath(new URL("../src/generated/assets.ts", import.meta.url));

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(target, render());
  console.log(`Wrote ${target}`);
}
